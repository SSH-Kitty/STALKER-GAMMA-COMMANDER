"""Template for a new COMMANDER UI translation.

To add a new language:

1. Copy this file to ``commander_gui/locales/<code>.py`` (a two-letter
   ISO 639-1 code, e.g. ``it.py`` for Italian).
2. Fill in every value below with its translation - leave a key's value
   as ``""`` and ``tr()`` will just fall back to showing the English text
   for it (see ``commander_gui/i18n.py``), so a partial translation is
   safe to ship and finish later.
3. Keep proper nouns/brand terms untranslated (GAMMA, STALKER, Anomaly,
   COMMANDER, Mod Organizer 2/MO2, Winetricks, Proton/GE-Proton, FOMOD,
   Nexus, specific mod/repo names, filenames such as settings.json/
   modlist.txt, environment variables) - matching every other locale
   file in this directory.
4. Keep every ``{placeholder}`` (e.g. ``{name}``, ``{path}``, ``{exc}``)
   exactly as it appears in the English key - these are filled in with
   real values at runtime via ``str.format()``, and a missing/renamed
   placeholder makes that string silently fall back to English rather
   than crash (see ``tr()``'s own docstring) - so it is safe, but still
   worth getting right so the translation actually shows.
5. Add ``("<code>", "<Native name>", "<English name>")`` to
   ``LANGUAGE_INFO`` in ``commander_gui/i18n.py`` so it appears in the
   Settings page's language picker.

This file's keys are the exact, complete set of English source strings
used throughout ``commander_gui/ui/*.py`` and ``Steamdeck/`` (Steam Deck
Mode) as of this template's generation - the same set every other locale
file translates. Both interfaces share one ``tr()`` and one set of locale
tables, so a translation you add here covers them together.
"""

